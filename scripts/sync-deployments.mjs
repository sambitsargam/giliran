// Copies contract addresses and ABIs from the Foundry project into the web app.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "web/src/config");
mkdirSync(out, { recursive: true });

const deployments = readFileSync(join(root, "contracts/deployments/base-sepolia.json"), "utf8");
writeFileSync(join(out, "deployments.json"), deployments);

const contracts = {
  Circle: "circleAbi",
  CircleFactory: "circleFactoryAbi",
  SavingsRegistry: "savingsRegistryAbi",
  MockUSDC: "mockUsdcAbi",
  FakeCircleDemo: "fakeCircleDemoAbi",
};
const artifacts = join(root, "contracts/out");
if (existsSync(artifacts)) {
  let src = "// Generated by scripts/sync-deployments.mjs from Foundry artifacts. Do not edit.\n\n";
  for (const [name, id] of Object.entries(contracts)) {
    const { abi } = JSON.parse(readFileSync(join(artifacts, `${name}.sol`, `${name}.json`), "utf8"));
    src += `export const ${id} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
  }
  writeFileSync(join(out, "abis.ts"), src);
  console.log("synced deployments.json and abis.ts");
} else {
  console.log("synced deployments.json (no forge artifacts; run forge build for ABIs)");
}
